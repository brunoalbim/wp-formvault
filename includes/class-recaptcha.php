<?php
/**
 * Google Cloud reCAPTCHA assessment client.
 *
 * @package WPFormVault
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

class WPFV_Recaptcha {
	const HEALTH_OPTION = 'wpfv_recaptcha_health';

	/** Return whether all server-side credentials are available. */
	public static function configured() {
		$settings = WPFV_Settings::get_global();
		return ! empty( $settings['recaptcha_project_id'] ) && ! empty( $settings['recaptcha_site_key'] ) && ! empty( $settings['recaptcha_api_key'] );
	}

	/** Return the stable action name used on the client and server. */
	public static function action_name( $form_id ) {
		$form_id = sanitize_key( $form_id );
		$label   = preg_replace( '/[^a-zA-Z0-9_\/]/', '_', $form_id );
		return substr( 'wpfv_' . $label, 0, 91 ) . '_' . substr( hash( 'sha256', $form_id ), 0, 8 );
	}

	/** Return the latest provider health event for the admin UI. */
	public static function health() {
		$health = get_option( self::HEALTH_OPTION, array() );
		return is_array( $health ) ? $health : array();
	}

	/**
	 * Assess one form token.
	 *
	 * @param string $token Token generated by grecaptcha.enterprise.execute().
	 * @param string $form_id Registered form identifier.
	 * @param float  $threshold Minimum accepted score.
	 * @return array Assessment decision and safe risk metadata.
	 */
	public function assess( $token, $form_id, $threshold ) {
		if ( ! self::configured() ) {
			return $this->configuration_error( 'missing_credentials', __( 'As credenciais do reCAPTCHA estão incompletas.', 'wp-formvault' ) );
		}

		$token = is_string( $token ) ? trim( $token ) : '';
		if ( '' === $token ) {
			return $this->spam( 'missing_token' );
		}
		if ( strlen( $token ) > 4096 ) {
			return $this->spam( 'invalid_token' );
		}

		$settings = WPFV_Settings::get_global();
		$action   = self::action_name( $form_id );
		$event    = array(
			'token'          => $token,
			'siteKey'        => $settings['recaptcha_site_key'],
			'expectedAction' => $action,
			'userAgent'      => isset( $_SERVER['HTTP_USER_AGENT'] ) && is_scalar( $_SERVER['HTTP_USER_AGENT'] ) ? sanitize_text_field( wp_unslash( $_SERVER['HTTP_USER_AGENT'] ) ) : '',
		);
		$client_ip = WPFV_Antispam::client_ip();
		if ( $client_ip ) {
			$event['userIpAddress'] = $client_ip;
		}

		$url = sprintf(
			'https://recaptchaenterprise.googleapis.com/v1/projects/%s/assessments',
			rawurlencode( $settings['recaptcha_project_id'] )
		);
		$response = wp_remote_post(
			$url,
			array(
				'timeout' => 8,
				'headers' => array(
					'Content-Type'   => 'application/json; charset=utf-8',
					'X-Goog-Api-Key' => $settings['recaptcha_api_key'],
				),
				'body'    => wp_json_encode( array( 'event' => $event ) ),
			)
		);

		if ( is_wp_error( $response ) ) {
			return $this->unavailable( 'network_error', $response->get_error_message() );
		}

		$code = (int) wp_remote_retrieve_response_code( $response );
		$body = json_decode( wp_remote_retrieve_body( $response ), true );
		if ( 429 === $code || $code >= 500 ) {
			return $this->unavailable( 'provider_unavailable', 'HTTP ' . $code );
		}
		if ( in_array( $code, array( 400, 401, 403 ), true ) ) {
			return $this->configuration_error( 'provider_configuration', $this->provider_error_detail( $code, $body, $settings, $token ) );
		}
		if ( $code < 200 || $code >= 300 || ! is_array( $body ) ) {
			return $this->spam( 'invalid_response' );
		}

		$properties = isset( $body['tokenProperties'] ) && is_array( $body['tokenProperties'] ) ? $body['tokenProperties'] : array();
		$risk       = isset( $body['riskAnalysis'] ) && is_array( $body['riskAnalysis'] ) ? $body['riskAnalysis'] : array();
		$metadata   = array(
			'provider'        => 'google_recaptcha',
			'assessment_name' => isset( $body['name'] ) && is_scalar( $body['name'] ) ? sanitize_text_field( $body['name'] ) : '',
			'score'           => isset( $risk['score'] ) && is_numeric( $risk['score'] ) ? (float) $risk['score'] : null,
			'reasons'         => isset( $risk['reasons'] ) && is_array( $risk['reasons'] ) ? $this->sanitize_reasons( $risk['reasons'] ) : array(),
		);

		if ( empty( $properties['valid'] ) ) {
			$metadata['reason'] = 'invalid_token';
			if ( ! empty( $properties['invalidReason'] ) && is_scalar( $properties['invalidReason'] ) ) {
				$metadata['provider_reason'] = sanitize_key( $properties['invalidReason'] );
			}
			$this->mark_healthy();
			return array( 'decision' => 'spam', 'risk_data' => $metadata );
		}

		if ( empty( $properties['action'] ) || ! is_scalar( $properties['action'] ) || ! hash_equals( $action, (string) $properties['action'] ) ) {
			$metadata['reason'] = 'action_mismatch';
			$this->mark_healthy();
			return array( 'decision' => 'spam', 'risk_data' => $metadata );
		}

		$expected_host = strtolower( (string) wp_parse_url( home_url( '/' ), PHP_URL_HOST ) );
		$actual_host   = isset( $properties['hostname'] ) && is_scalar( $properties['hostname'] ) ? strtolower( sanitize_text_field( $properties['hostname'] ) ) : '';
		if ( $expected_host && ( ! $actual_host || ! hash_equals( $expected_host, $actual_host ) ) ) {
			$metadata['reason'] = 'hostname_mismatch';
			$this->mark_healthy();
			return array( 'decision' => 'spam', 'risk_data' => $metadata );
		}

		$this->mark_healthy();
		if ( null === $metadata['score'] || $metadata['score'] < (float) $threshold ) {
			$metadata['reason'] = 'low_score';
			return array( 'decision' => 'spam', 'risk_data' => $metadata );
		}

		$metadata['reason'] = 'accepted';
		return array( 'decision' => 'accept', 'risk_data' => $metadata );
	}

	private function sanitize_reasons( $reasons ) {
		$sanitized = array();
		foreach ( $reasons as $reason ) {
			if ( is_scalar( $reason ) ) {
				$sanitized[] = sanitize_key( $reason );
			}
		}
		return array_values( array_filter( $sanitized ) );
	}

	/** Store a short diagnostic after removing known credentials and token-like values. */
	private function provider_error_detail( $code, $body, $settings, $token ) {
		$parts = array( 'HTTP ' . (int) $code );
		$error = is_array( $body ) && isset( $body['error'] ) && is_array( $body['error'] ) ? $body['error'] : array();
		if ( isset( $error['status'] ) && is_scalar( $error['status'] ) && preg_match( '/^[A-Z][A-Z_]{1,63}$/', (string) $error['status'] ) ) {
			$parts[] = (string) $error['status'];
		}
		if ( isset( $error['details'] ) && is_array( $error['details'] ) ) {
			foreach ( $error['details'] as $item ) {
				$reason = is_array( $item ) && isset( $item['reason'] ) && is_scalar( $item['reason'] ) ? (string) $item['reason'] : '';
				if ( preg_match( '/^[A-Z][A-Z0-9_]{1,63}$/', $reason ) ) {
					$parts[] = $reason;
					break;
				}
			}
		}
		$message = isset( $error['message'] ) && is_scalar( $error['message'] ) ? (string) $error['message'] : '';
		if ( $message ) {
			foreach ( array( $token, isset( $settings['recaptcha_api_key'] ) ? $settings['recaptcha_api_key'] : '', isset( $settings['recaptcha_site_key'] ) ? $settings['recaptcha_site_key'] : '' ) as $secret ) {
				if ( is_string( $secret ) && '' !== $secret ) $message = str_replace( $secret, '[valor omitido]', $message );
			}
			$message = preg_replace( '/AIza[0-9A-Za-z_-]{20,}|[A-Za-z0-9_-]{64,}/', '[valor omitido]', $message );
			$message = substr( sanitize_text_field( $message ), 0, 250 );
			if ( $message ) $parts[] = $message;
		}
		return implode( ' · ', array_unique( $parts ) );
	}

	private function spam( $reason ) {
		return array(
			'decision'  => 'spam',
			'risk_data' => array( 'provider' => 'google_recaptcha', 'reason' => sanitize_key( $reason ), 'score' => null, 'reasons' => array() ),
		);
	}

	private function unavailable( $reason, $detail ) {
		$this->save_health( 'warning', __( 'O reCAPTCHA está temporariamente indisponível; as proteções locais continuam ativas.', 'wp-formvault' ), $detail );
		return array(
			'decision'  => 'degraded',
			'risk_data' => array( 'provider' => 'google_recaptcha', 'reason' => sanitize_key( $reason ), 'score' => null, 'reasons' => array() ),
		);
	}

	private function configuration_error( $reason, $detail ) {
		$this->save_health( 'error', __( 'O reCAPTCHA não pôde validar envios. Revise as credenciais e a configuração do projeto.', 'wp-formvault' ), $detail );
		return array(
			'decision'  => 'spam',
			'risk_data' => array( 'provider' => 'google_recaptcha', 'reason' => sanitize_key( $reason ), 'score' => null, 'reasons' => array(), 'provider_detail' => sanitize_text_field( $detail ) ),
		);
	}

	private function mark_healthy() {
		$current = self::health();
		if ( 'success' !== ( isset( $current['status'] ) ? $current['status'] : '' ) || empty( $current['time'] ) || absint( $current['time'] ) < time() - ( 6 * HOUR_IN_SECONDS ) ) {
			$this->save_health( 'success', __( 'O reCAPTCHA validou envios recentemente.', 'wp-formvault' ), '' );
		}
	}

	private function save_health( $status, $message, $detail ) {
		$status  = sanitize_key( $status );
		$message = sanitize_text_field( $message );
		$detail  = sanitize_text_field( $detail );
		$current = self::health();
		if (
			$status === ( isset( $current['status'] ) ? $current['status'] : '' ) &&
			$message === ( isset( $current['message'] ) ? $current['message'] : '' ) &&
			$detail === ( isset( $current['detail'] ) ? $current['detail'] : '' ) &&
			! empty( $current['time'] ) &&
			absint( $current['time'] ) >= time() - ( 5 * MINUTE_IN_SECONDS )
		) {
			return;
		}

		update_option(
			self::HEALTH_OPTION,
			array(
				'status'  => $status,
				'message' => $message,
				'detail'  => $detail,
				'time'    => time(),
			),
			false
		);
	}
}
